function complete(workpackId, summary) {
  return { workpackId, proofState: 'contract-proof-complete', summary };
}

function partial(workpackId, summary) {
  return { workpackId, proofState: 'contract-proof-partial', summary };
}

async function writeProofPack(pack, commit, checkedAt) {
  const dir = join(proofRoot, pack.workpackId);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, '00-source-snapshot.md'), sourceSnapshot(pack, commit, checkedAt));
  await writeFile(join(dir, '01-contract-proof.log'), contractProofLog(pack));
  await writeFile(join(dir, '13-security-negative-proof.log'), securityProofLog(pack));
  await writeFile(join(dir, '15-manual-platform-proof.md'), manualPlatformProof(pack));
  await writeFile(join(dir, '16-validation-commands.log'), commands.map((entry) => entry.command).join('\n') + '\n');
  await writeFile(
    join(dir, 'proof-summary.json'),
    `${JSON.stringify(summaryJson(pack, commit, checkedAt), null, 2)}\n`
  );
}

